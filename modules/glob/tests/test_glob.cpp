//     directories (fs + cwd + symlink behavior).
//   - SKIPPED(S1) stress.test.ts (whole file): scan stress / GC pressure.
//   - SKIPPED(S1) leak.test.ts (whole file): RSS leak thresholds on scan.
//   - SKIPPED(S1) proto.test.ts (whole file): JS prototype/constructor

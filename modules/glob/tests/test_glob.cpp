// source: match.test.ts > test("deeply nested braces do not overflow depth counters")
void test_deeply_nested_braces() {
    const std::string opens(300, '{');
    const std::string closes(300, '}');
    constexpr std::string_view src{"deeply nested braces"};

    // First branch matches; branch skipping must scan past >255 nested braces
    // to find the closing brace of the outer group.
    std::string pattern{"{a," + opens + closes + "}"};
    check_match(pattern, "a", true, src);
    check_match(pattern, "b", false, src);

    // Deeply nested braces in the first (non-matching) branch, second branch matches.
    pattern = "{" + opens + closes + ",a}";
    check_match(pattern, "a", true, src);

    // Deep nest with content, surrounded by matching branches on both sides.
    pattern = "{a," + opens + "x" + closes + ",b}";
    check_match(pattern, "a", true, src);
    check_match(pattern, "b", true, src);
    check_match(pattern, "y", false, src);

    // Same shape inside a wildcard backtrack.
    pattern = "*{a," + opens + closes + "}";
    check_match(pattern, "za", true, src);

    // >32767 consecutive `{`: the group never closes, so nothing matches.
    const std::string unclosed(40000, '{');
    check_match(unclosed, "a", false, src);
    check_match(unclosed, "{", false, src);
}


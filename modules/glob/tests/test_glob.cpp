// JS String.prototype.split("\n"): empty pieces are kept, including a
// trailing one when the text ends with '\n'.
std::vector<std::string_view> split_lines(std::string_view text) {
    std::vector<std::string_view> parts;
    std::size_t start{0};
    while (true) {
        const auto pos{text.find('\n', start)};
        if (pos == std::string_view::npos) {
            parts.push_back(text.substr(start));
            break;
        }
        parts.push_back(text.substr(start, pos - start));
        start = pos + 1;
    }
    return parts;
}

// source: match.test.ts > test("braces") fixture table:
// `matched` (every filelist entry the pattern matches, in file order) must
// equal the corresponding matched-N.txt contents (toEqual semantics).
void test_brace_fixtures() {
    const auto allFilePaths{split_lines(kGlobFixtureFileList)};
    int index{0};
    for (const auto& fixture : kGlobFixtureCases) {
        const auto shouldMatch{split_lines(fixture.expected)};
        std::vector<std::string_view> matched;
        for (const auto& filepath : allFilePaths) {
            if (match(fixture.pattern, filepath)) {
                matched.push_back(filepath);
            }
        }
        ++gChecks;
        if (matched != shouldMatch) {
            report_failure(std::format(
                "[braces fixtures[{}]] pattern \"{}\": {} matches, expected {}", index,
                fixture.pattern, matched.size(), shouldMatch.size()));
            // Print the first divergence to aid debugging.
            const auto n{std::min(matched.size(), shouldMatch.size())};
            for (std::size_t i{0}; i < n; ++i) {
                if (matched[i] != shouldMatch[i]) {
                    std::println("    first divergence at [{}]: got \"{}\", expected \"{}\"", i,
                                 matched[i], shouldMatch[i]);
                    break;
                }
            }
        }
        ++index;
    }
}

// ── scan (real filesystem traversal) ────────────────────────────────────────
//
// Builds a temporary directory tree in-process, runs mbun::glob::scan over it,
// and verifies the matched relative paths. Covers the DEFERRED scan surface:
// **/*/?/[...]/{a,b}, dotfiles (default + dot:true + leading-dot pattern),
// onlyFiles, absolute, and directory pruning. Not a port of bun's scan.test.ts
// (which diffs against fast-glob over the bun repo); the semantics asserted
// here match bun's GlobWalker eval logic.

void write_file(const std::filesystem::path& p, std::string_view contents) {
    std::filesystem::create_directories(p.parent_path());
    std::ofstream f{p};
    f << contents;
}

std::filesystem::path make_scan_tree() {
    std::error_code ec;
    const auto uniq{std::chrono::steady_clock::now().time_since_epoch().count()};
    const std::filesystem::path base{std::filesystem::temp_directory_path(ec)
                                     / std::format("mbun-glob-scan-{}", uniq)};
    std::filesystem::remove_all(base, ec);
    std::filesystem::create_directories(base);
    write_file(base / "a.ts", "");
    write_file(base / "a.js", "");
    write_file(base / "b.txt", "");
    write_file(base / ".hidden.ts", "");
    write_file(base / "src" / "foo.ts", "");
    write_file(base / "src" / "bar.js", "");
    write_file(base / "src" / "nested" / "deep.ts", "");
    write_file(base / "src" / "nested" / ".secret.ts", "");
    write_file(base / "node_modules" / "pkg" / "index.js", "");
    write_file(base / ".git" / "config", "");
    std::filesystem::create_directories(base / "emptydir");
    return base;
}

std::vector<std::string> sorted(std::vector<std::string> v) {
    std::ranges::sort(v);
    return v;
}

void check_scan(std::string_view label, std::vector<std::string> got,
                std::vector<std::string> expected) {
    ++gChecks;
    const std::vector<std::string> g{sorted(std::move(got))};
    const std::vector<std::string> e{sorted(std::move(expected))};
    if (g != e) {
        std::string gotStr;
        for (const auto& s : g) {
            gotStr += s + " ";
        }
        std::string expStr;
        for (const auto& s : e) {
            expStr += s + " ";
        }
        report_failure(std::format("scan[{}]: got [{}] expected [{}]", label, gotStr, expStr));
    }
}

void test_scan() {
    using mbun::glob::scan;
    using mbun::glob::ScanOptions;

    const std::filesystem::path base{make_scan_tree()};
    const std::string cwd{base.string()};
    auto opt = [&](ScanOptions o) {
        o.cwd = cwd;
        return o;
    };

    check_scan("*.ts", scan("*.ts", opt({})), {"a.ts"});
    check_scan("**/*.ts", scan("**/*.ts", opt({})),
               {"a.ts", "src/foo.ts", "src/nested/deep.ts"});
    check_scan("src/*.ts", scan("src/*.ts", opt({})), {"src/foo.ts"});
    check_scan("src/**/*.ts", scan("src/**/*.ts", opt({})),
               {"src/foo.ts", "src/nested/deep.ts"});
    check_scan("**/*.js", scan("**/*.js", opt({})),
               {"a.js", "src/bar.js", "node_modules/pkg/index.js"});
    check_scan("**/node_modules/**/*.js", scan("**/node_modules/**/*.js", opt({})),
               {"node_modules/pkg/index.js"});
    check_scan("*.{ts,js}", scan("*.{ts,js}", opt({})), {"a.ts", "a.js"});
    check_scan("a.?s", scan("a.?s", opt({})), {"a.ts", "a.js"});
    check_scan("[ab].txt", scan("[ab].txt", opt({})), {"b.txt"});

    // dotfiles: excluded by default, included with dot:true, and matched by a
    // pattern component that itself starts with a literal '.'.
    ScanOptions dotOpt{};
    dotOpt.dot = true;
    check_scan("*.ts dot:true", scan("*.ts", opt(dotOpt)), {"a.ts", ".hidden.ts"});
    check_scan(".*", scan(".*", opt({})), {".hidden.ts"});
    check_scan("**/*.ts dot:true", scan("**/*.ts", opt(dotOpt)),
               {"a.ts", ".hidden.ts", "src/foo.ts", "src/nested/deep.ts",
                "src/nested/.secret.ts"});

    // onlyFiles:false includes matching directories.
    ScanOptions dirsOpt{};
    dirsOpt.onlyFiles = false;
    check_scan("src onlyFiles:false", scan("src", opt(dirsOpt)), {"src"});
    check_scan("* onlyFiles:false", scan("*", opt(dirsOpt)),
               {"a.ts", "a.js", "b.txt", "src", "node_modules", "emptydir"});

    // absolute paths.
    const std::string absTs{(base / "a.ts").generic_string()};
    check_scan("*.ts absolute", scan("*.ts", opt([&] {
                   ScanOptions o{};
                   o.absolute = true;
                   return o;
               }())),
               {absTs});

    std::error_code ec;
    std::filesystem::remove_all(base, ec);
}


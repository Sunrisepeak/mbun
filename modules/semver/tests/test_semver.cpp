int gChecks{0};
int gFailures{0};
constexpr int MAX_FAILURE_PRINTS{25};

void report_failure(std::string_view what) {
    ++gFailures;
    if (gFailures <= MAX_FAILURE_PRINTS) {
        std::println("  FAIL {}", what);
    }
}

void check_order(std::string_view a, std::string_view b, int expected, std::string_view src) {
    ++gChecks;
    int actual{order(a, b)};
    if (actual != expected) {
        report_failure(std::format("[{}] order(\"{}\", \"{}\") = {}, expected {}", src, a, b,
                                   actual, expected));
    }
}

void check_satisfies(std::string_view version, std::string_view range, bool expected,
                     std::string_view src) {
    ++gChecks;
    bool actual{satisfies(version, range)};
    if (actual != expected) {
        report_failure(std::format("[{}] satisfies(\"{}\", \"{}\") = {}, expected {}", src, version,
                                   range, actual, expected));
    }
}


// Invalid or non-full version strings must never satisfy a concrete range.
// A full [major.minor.patch] version is required; wildcards, missing
// components, empty/garbage input and malformed cores are all rejected.
// Every pair below is false in both bun and node-semver. ("1.2.3-" is
// deliberately absent: bun parses a trailing '-' as an EMPTY pre-release, i.e.
// treats it as "1.2.3" and accepts it — a documented bun/node-semver
// divergence; bun's behavior is the pinned standard here.)
constexpr std::string_view kInvalidVersions[]{
    "",      "a.b.c", "1.2.3.4", "1.2",  "1",    "not-a-version", "1.2.x",
    "1.x.3", "x",     "*",       "1..2", ".1.2", "1.2.",          "v",
    "=",     "-1.2.3",
};
constexpr std::string_view kConcreteRanges[]{"*", ">=0.0.0", "1.2.3", "^1.0.0"};

void test_invalid_version_rejection() {
    for (std::string_view v : kInvalidVersions) {
        for (std::string_view r : kConcreteRanges) {
            check_satisfies(v, r, false, "invalid-version-rejection");
        }
    }
}


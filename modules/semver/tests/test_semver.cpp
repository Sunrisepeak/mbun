// semver.test.ts > describe "Bun.semver.satisfies()" > test "pre-release snapshot"
// semver-fixture.js unsortedPrereleases sorted with order() must match the
// snapshot in semver.test.ts.snap (JS Array#sort is stable => stable_sort).
void test_prerelease_snapshot() {
    static_assert(std::size(kUnsortedPrereleases) == std::size(kSortedPrereleases));
    std::vector<std::string_view> sorted(std::begin(kUnsortedPrereleases),
                                         std::end(kUnsortedPrereleases));
    std::ranges::stable_sort(sorted, [](std::string_view a, std::string_view b) {
        return order(a, b) < 0;
    });
    for (std::size_t i{0}; i < sorted.size(); ++i) {
        ++gChecks;
        if (sorted[i] != kSortedPrereleases[i]) {
            report_failure(std::format("[snapshot] index {}: got \"{}\", expected \"{}\"", i,
                                       sorted[i], kSortedPrereleases[i]));
        }
    }
    // Sort invariant: adjacent elements must be non-decreasing under order().
    for (std::size_t i{1}; i < sorted.size(); ++i) {
        ++gChecks;
        if (order(sorted[i - 1], sorted[i]) > 0) {
            report_failure(std::format("[snapshot] adjacency violated at {}: \"{}\" > \"{}\"", i,
                                       sorted[i - 1], sorted[i]));
        }
    }
}

